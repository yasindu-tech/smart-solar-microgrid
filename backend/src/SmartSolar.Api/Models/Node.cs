using MongoDB.Bson;
using MongoDB.Bson.Serialization.Attributes;

namespace SmartSolar.Api.Models;

/// <summary>One operating window on one day, e.g. Mon 06:00-18:00.</summary>
public class ScheduleWindow
{
    // Three-letter day name as stored in Mongo: Mon, Tue, Wed, Thu, Fri, Sat, Sun.
    [BsonElement("dayOfWeek")]
    public string DayOfWeek { get; set; } = string.Empty;

    // Opening time as "HH:mm", 24-hour, zero padded.
    [BsonElement("openTime")]
    public string OpenTime { get; set; } = string.Empty;

    // Closing time as "HH:mm", 24-hour, zero padded.
    [BsonElement("closeTime")]
    public string CloseTime { get; set; } = string.Empty;
}

/// <summary>GPS position and human-readable address of a hub.</summary>
public class NodeLocation
{
    [BsonElement("latitude")]
    public double Latitude { get; set; }

    [BsonElement("longitude")]
    public double Longitude { get; set; }

    [BsonElement("addressLine")]
    public string AddressLine { get; set; } = string.Empty;
}

/// <summary>
/// A microgrid node. Stored in the "SolarStationInfo" collection.
/// There is no hard delete - a node is only ever deactivated (REQ-NODE EC-4).
/// </summary>
public class Node
{
    // MongoDB auto-generated document identifier.
    [BsonId]
    [BsonRepresentation(BsonType.ObjectId)]
    public string? Id { get; set; }

    // Human-readable unique id, e.g. "ND-0003". Generated by the counter.
    [BsonElement("nodeId")]
    public string NodeId { get; set; } = string.Empty;

    [BsonElement("name")]
    public string Name { get; set; } = string.Empty;

    [BsonElement("location")]
    public NodeLocation Location { get; set; } = new();

    // Total node capacity in kWh.
    [BsonElement("capacityKwh")]
    public double CapacityKwh { get; set; }

    // Number of battery storage slots at this hub.
    [BsonElement("batterySlotCount")]
    public int BatterySlotCount { get; set; }

    // "AC" or "DC" - kept for reporting.
    [BsonElement("type")]
    public string Type { get; set; } = "AC";

    [BsonElement("schedule")]
    public List<ScheduleWindow> Schedule { get; set; } = new();

    // False once deactivated. Drives BR-20 (invisible and unbookable).
    [BsonElement("isActive")]
    public bool IsActive { get; set; } = true;

    // UserId of the Backoffice account that created it, e.g. "USR-0001".
    [BsonElement("createdBy")]
    public string CreatedBy { get; set; } = string.Empty;

    [BsonElement("createdAt")]
    public DateTime CreatedAt { get; set; }

    [BsonElement("updatedAt")]
    public DateTime UpdatedAt { get; set; }
}
